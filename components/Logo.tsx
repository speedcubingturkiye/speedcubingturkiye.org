type Props = Omit<SVGProps<SVGSVGElement>, 'viewBox'> & {
  variant: 'long' | 'mark'
  /** inverted = the kit's white version for red and black backgrounds */
  tone?: 'default' | 'inverted'
  /** inverted only: keep the default tone's box and let the white frames overflow it. Where the two tones swap in place
   *  (the header's light/dark logo), both then snap to the same pixel grid and the art never moves by a pixel. */
  sameBox?: boolean
}

export function Logo({ variant, tone = 'default', sameBox = false, className, style, ...rest }: Props) {
  const inverted = tone === 'inverted'
  const ownBox = inverted && !sameBox
  const body = inverted ? '#fff' : 'var(--color-bg)' // crescent and star fill
  const line = inverted ? '#fff' : RED
  const text = inverted ? '#fff' : 'currentColor'
  const width = variant === 'long' ? 3221.01 : ownBox ? 815.25 : 794.04
  const viewBox = ownBox ? `0 -21.22 ${width} 424.2` : `0 0 ${width} 381.76`
  return (
    <svg
      viewBox={viewBox}
      role="img"
      aria-label="Speedcubing Türkiye"
      className={className}
      style={inverted && sameBox ? { overflow: 'visible', ...style } : style}
      {...rest}
    >
      {(inverted ? LINES_UNDER_FRAME : LINES).map((points) => (
        <polygon key={points} points={points} fill={line} />
      ))}
      {inverted &&
        SQUARES.map(([x, y]) => (
          <rect key={`frame-${x}-${y}`} x={x - 15} y={y - 15} width={110} height={110} fill="#fff" transform={`rotate(-45 ${x + 40} ${y + 40})`} />
        ))}
      {SQUARES.map(([x, y]) => (
        <rect key={`${x}-${y}`} x={x} y={y} width={80} height={80} fill={RED} transform={`rotate(-45 ${x + 40} ${y + 40})`} />
      ))}
      <path d={CRESCENT_BODY} fill={body} />
      <path d={CRESCENT_RING} fill={RED} />
      <polygon points={STAR_BODY} fill={body} />
      <path d={STAR_RING} fill={RED} />
      {variant === 'long' && WORDMARK.map((d, i) => <path key={i} d={d} fill={text} />)}
    </svg>
  )
}
